//! ROADMAP H1, stage 1: `Hip::lower_kernel` spells the memory and control subset as HIP C++ and declines everything NVIDIA-specific
//! by name, saying why. **No HIP compiler or AMD device was available**: these tests pin the source shape. The
//! `nvrtc-syntax-check` feature additionally compiles the text with NVRTC, which shows it is well-formed C++ with the shared
//! `__global__` spellings, nothing more.

use baracuda_hip_emit::Hip;
use unpopped::backend::{Backend, LowerError};
use unpopped::exec::{AllocDecl, ExecId, Extent, LaunchShape, MemorySpace, Scope};
use unpopped::ir::{BinaryOp, ScalarExpr};
use unpopped::kernel::{
    BarrierKind, Block, BufferRole, KernelFn, LocalDecl, Param, Place, Stmt, check_kernel,
};
use unpopped_vocab::{ElementKind, TargetId};

const F32: ElementKind = ElementKind::F32;
const I32: ElementKind = ElementKind::I32;
const U32: ElementKind = ElementKind::U32;

/// `if i < n { out[i] = x[i] * 2.0 }` with `i = blockIdx.x * blockDim.x + threadIdx.x`.
fn scale() -> KernelFn {
    let u = |e: ScalarExpr| Box::new(e);
    let i = ScalarExpr::Add(
        u(ScalarExpr::Mul(
            u(ScalarExpr::Exec(ExecId::BlockIdx(0))),
            u(ScalarExpr::Exec(ExecId::BlockDim(0))),
        )),
        u(ScalarExpr::Exec(ExecId::ThreadIdx(0))),
    );
    let at_i = |buffer| Place::Logical {
        buffer,
        coords: vec![ScalarExpr::Local(1)],
    };
    KernelFn::new(
        "scale",
        F32,
        vec![
            Param::buffer("x", F32, BufferRole::Read, Some(1)),
            Param::buffer("out", F32, BufferRole::Write, Some(1)),
            Param::scalar("n", U32, 0),
        ],
        vec![
            LocalDecl::scalar(U32),
            LocalDecl::scalar(U32),
            LocalDecl::scalar(F32),
        ],
        Block(vec![
            Stmt::Let { local: 1, init: i },
            Stmt::If {
                cond: ScalarExpr::Binary(
                    BinaryOp::CmpLt,
                    u(ScalarExpr::Local(1)),
                    u(ScalarExpr::Local(0)),
                ),
                then: Block(vec![
                    Stmt::Load {
                        local: 2,
                        place: at_i(0),
                    },
                    Stmt::Store {
                        place: at_i(1),
                        value: ScalarExpr::Mul(u(ScalarExpr::Local(2)), u(ScalarExpr::Const(2.0))),
                    },
                ]),
                els: Block(Vec::new()),
            },
        ]),
    )
    .with_launch(LaunchShape::new([256, 1, 1], [4, 1, 1]))
}

/// Shared memory and a block barrier.
fn shared_barrier() -> KernelFn {
    KernelFn::new(
        "red",
        I32,
        vec![Param::buffer("out", I32, BufferRole::ReadWrite, Some(1))],
        vec![LocalDecl::scalar(I32)],
        Block(vec![
            Stmt::Store {
                place: Place::Alloc {
                    alloc: 0,
                    index: ScalarExpr::Exec(ExecId::ThreadIdx(0)),
                },
                value: ScalarExpr::ConstInt(1, I32),
            },
            Stmt::Barrier {
                scope: Scope::Block,
                kind: BarrierKind::Full,
            },
        ]),
    )
    .with_allocs(vec![AllocDecl::new(
        "s",
        MemorySpace::Shared,
        I32,
        Extent::Static(4),
    )])
    .with_launch(LaunchShape::new([4, 1, 1], [1, 1, 1]))
}

fn lowered(k: &KernelFn) -> unpopped::backend::GeneratedKernel {
    check_kernel(k).unwrap_or_else(|e| panic!("the fixture is not well-formed: {e:?}"));
    Hip.lower_kernel(k)
        .unwrap_or_else(|e| panic!("expected a lowering, got {e:?}"))
}

#[test]
fn a_guarded_elementwise_kernel_lowers_to_hip_with_checked_addressing() {
    let g = lowered(&scale());
    assert_eq!(g.name, "baracuda_hip_kernel_scale");
    for want in [
        "// Generated by baracuda-hip-emit",
        "extern \"C\" __global__ void __launch_bounds__(256) baracuda_hip_kernel_scale(const float* p0, float* p1, Args_scale a)",
        "blockIdx.x",
        "blockDim.x",
        "threadIdx.x",
        "__trap();",
        "static_assert(sizeof(Args_scale)",
    ] {
        assert!(g.source.contains(want), "missing `{want}`:\n{}", g.source);
    }
    // Nothing of the CUDA emitter's identity or of NVIDIA-only text leaks in.
    for not in [
        "baracuda_cuda",
        "cp.async",
        "__CUDA_ARCH__",
        "asm volatile",
        "mbarrier",
    ] {
        assert!(!g.source.contains(not), "unexpected `{not}`:\n{}", g.source);
    }
    assert!(g.interface().is_some(), "the interface (ABI B) is attached");
}

#[test]
fn the_block_barrier_is_syncthreads_and_shared_is_shared() {
    let g = lowered(&shared_barrier());
    assert!(g.source.contains("__syncthreads();"), "{}", g.source);
    assert!(g.source.contains("__shared__ int sh0[4];"), "{}", g.source);
}

fn nvidia_kernel(body: Vec<Stmt>) -> KernelFn {
    KernelFn::new("n", I32, vec![], vec![LocalDecl::scalar(I32)], Block(body))
        .with_launch(LaunchShape::new([128, 1, 1], [1, 1, 1]))
}

fn declined(body: Vec<Stmt>, name: &str, reason: &str) {
    let k = nvidia_kernel(body);
    check_kernel(&k).unwrap_or_else(|e| panic!("`{name}` fixture is not well-formed: {e:?}"));
    match Hip.lower_kernel(&k) {
        Err(LowerError::UnsupportedKernel { detail }) => assert!(
            detail.contains(name) && detail.contains("HIP backend") && detail.contains(reason),
            "decline must name `{name}`, the HIP backend and `{reason}`: {detail}"
        ),
        other => panic!("`{name}` must be refused by name, got {other:?}"),
    }
}

/// NVIDIA-only statements are declined, naming the statement and saying why; none becomes a `__syncthreads()` or an `asm`.
#[test]
fn nvidia_only_statements_are_declined_by_name_with_a_reason() {
    declined(vec![Stmt::AsyncCommit], "AsyncCommit", "cp.async");
    declined(
        vec![Stmt::GridDepWait],
        "GridDepWait",
        "other manufacturers",
    );
    declined(vec![Stmt::WgmmaCommit], "WgmmaCommit", "tensor-core");
    // A named barrier waits for `count` threads; it must not become a whole-block `__syncthreads()`.
    let k = nvidia_kernel(vec![Stmt::Barrier {
        scope: Scope::Block,
        kind: BarrierKind::Named { id: 1, count: 64 },
    }]);
    check_kernel(&k).expect("well-formed");
    match Hip.lower_kernel(&k) {
        Err(LowerError::UnsupportedKernel { detail }) => {
            assert!(
                detail.contains("Barrier") && detail.contains("Named"),
                "{detail}"
            )
        }
        other => panic!("a named barrier must be refused, got {other:?}"),
    }
}

/// `Cast` has no HIP spelling in stage 1 (the AMD conversion semantics are not checked): refused by node name.
#[test]
fn a_cast_expression_is_declined_by_name() {
    let k = KernelFn::new(
        "c",
        F32,
        vec![],
        vec![LocalDecl::scalar(F32)],
        Block(vec![Stmt::Let {
            local: 0,
            init: ScalarExpr::Cast(
                Box::new(ScalarExpr::ConstInt(1, I32)),
                unpopped::ir::CastSpec {
                    to: F32,
                    round: unpopped::ir::RoundMode::NearestEven,
                    sat: unpopped::ir::Saturation::Wrap,
                },
            ),
        }]),
    );
    check_kernel(&k).expect("well-formed");
    match Hip.lower_kernel(&k) {
        Err(LowerError::UnsupportedKernel { detail }) => {
            assert!(
                detail.contains("Cast") && detail.contains("HIP backend"),
                "{detail}"
            )
        }
        other => panic!("a Cast must be refused, got {other:?}"),
    }
}

#[test]
fn the_plan_path_and_dtype_gate_decline() {
    assert_eq!(Hip.name(), "hip");
    assert_eq!(Hip.provider(), "baracuda");
    assert_eq!(
        Hip.supports_dtype(F32, TargetId::parse("cuda:sm80").expect("token")),
        unpopped::backend::DtypeSupport::Unsupported
    );
}

#[cfg(feature = "nvrtc-syntax-check")]
#[test]
fn the_emitted_text_is_well_formed_cpp() {
    use baracuda_cuda_emit::NvrtcCompiler;
    use unpopped::jit::Compiler;
    let nv = NvrtcCompiler::new(TargetId::parse("cuda:sm80").expect("token")).expect("nvrtc");
    for k in [scale(), shared_barrier()] {
        let g = lowered(&k);
        nv.compile(&g.source, &g.name, 5000)
            .unwrap_or_else(|e| panic!("NVRTC rejected the text: {e}\n{}", g.source));
    }
}
